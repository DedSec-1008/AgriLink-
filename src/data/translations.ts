export function formatString(template: string, ...args: (string | number)[]): string {
  let result = template;
  args.forEach((arg, index) => {
    // replace %1$s, %2$d, etc. and also %s, %d
    const regexIndexed = new RegExp(`%${index + 1}\\$[sd]`, 'g');
    const regexSimple = new RegExp(`%[sd]`);
    if (regexIndexed.test(result)) {
      result = result.replace(regexIndexed, String(arg));
    } else {
      result = result.replace(regexSimple, String(arg));
    }
  });
  return result;
}
